"""Storage for the series bible: JSON persistence plus Markdown export.

Local-first. Files live in a bible directory the user chooses (default
`.kdp_bible` inside the current working directory). No network access.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

from .models import Bible


class Storage:
    """Read/write a Bible as JSON files in a directory."""

    def __init__(self, directory: str | Path):
        self.directory = Path(directory)
        self.directory.mkdir(parents=True, exist_ok=True)

    def path(self, name: str) -> Path:
        return self.directory / f"{name}.json"

    def save(self, bible: Bible) -> None:
        self.directory.mkdir(parents=True, exist_ok=True)
        for entity, items in {
            "series_order": bible.series_order,
            "characters": bible.characters,
            "settings": bible.settings,
            "timeline": bible.timeline,
        }.items():
            data = [item.__dict__ if hasattr(item, "__dict__") else item for item in items]
            self.path(entity).write_text(
                json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
            )
        meta = {"series_name": bible.series_name}
        self.path("meta").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")

    def load(self) -> Bible:
        from .models import Character, Setting, TimelineEvent, SeriesBook

        series_name = ""
        meta_path = self.path("meta")
        if meta_path.exists():
            try:
                series_name = json.loads(meta_path.read_text(encoding="utf-8")).get(
                    "series_name", ""
                )
            except (json.JSONDecodeError, OSError):
                series_name = ""

        bible = Bible(series_name=series_name)
        for entity, cls in {
            "series_order": SeriesBook,
            "characters": Character,
            "settings": Setting,
            "timeline": TimelineEvent,
        }.items():
            path = self.path(entity)
            if not path.exists():
                continue
            try:
                raw = json.loads(path.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError):
                raw = []
            if isinstance(raw, list):
                for item in raw:
                    if isinstance(item, dict):
                        try:
                            getattr(bible, entity).append(cls(**item))
                        except TypeError:
                            # Skip malformed entries; validator will report them.
                            pass
        return bible

    def export_markdown(self, bible: Bible, path: Optional[str | Path] = None) -> str:
        """Render the bible as Markdown and return it (optionally write to file)."""
        markdown = render_markdown(bible)
        if path is not None:
            out_path = Path(path)
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(markdown, encoding="utf-8")
        return markdown


def render_markdown(bible: Bible) -> str:
    """Render the bible as Markdown and return it."""
    lines: list[str] = []
    lines.append(f"# {bible.series_name or 'Untitled Series'} — Series Bible")
    lines.append("")
    lines.append("Local-first KDP series bible generated by the kdp-series-bible CLI.")
    lines.append("Credit: Asdale Dynamics, LLC.")
    lines.append("")

    # Series order
    lines.append("## Series Order")
    lines.append("")
    if not bible.series_order:
        lines.append("*No books defined yet.*")
    else:
        lines.append("| Position | Title | Publication Date | ASIN | Notes |")
        lines.append("|----------|-------|------------------|------|-------|")
        for book in sorted(bible.series_order, key=lambda b: b.position):
            lines.append(
                f"| {book.position} | {book.title} | {book.publication_date} | {book.asin} | {book.notes} |"
            )
    lines.append("")

    # Characters
    lines.append("## Characters")
    lines.append("")
    if not bible.characters:
        lines.append("*No characters defined yet.*")
    else:
        lines.append("| ID | Name | Role | First Appearance |")
        lines.append("|----|------|------|------------------|")
        for char in bible.characters:
            lines.append(
                f"| {char.id} | {char.name} | {char.role} | {char.first_appearance} |"
            )
        lines.append("")
        for char in bible.characters:
            lines.append(f"### {char.name}")
            lines.append("")
            if char.description:
                lines.append(char.description)
                lines.append("")
            if char.age:
                lines.append(f"- Age: {char.age}")
            if char.occupation:
                lines.append(f"- Occupation: {char.occupation}")
            if char.notes:
                lines.append(f"- Notes: {char.notes}")
            lines.append("")

    # Settings
    lines.append("## Settings")
    lines.append("")
    if not bible.settings:
        lines.append("*No settings defined yet.*")
    else:
        lines.append("| ID | Name | Type | First Appearance |")
        lines.append("|----|------|------|------------------|")
        for setting in bible.settings:
            lines.append(
                f"| {setting.id} | {setting.name} | {setting.type} | {setting.first_appearance} |"
            )
        lines.append("")
        for setting in bible.settings:
            lines.append(f"### {setting.name}")
            lines.append("")
            if setting.description:
                lines.append(setting.description)
                lines.append("")
            if setting.notes:
                lines.append(f"- Notes: {setting.notes}")
            lines.append("")

    # Timeline
    lines.append("## Timeline")
    lines.append("")
    if not bible.timeline:
        lines.append("*No timeline events defined yet.*")
    else:
        lines.append("| Date | Title | Description |")
        lines.append("|------|-------|-------------|")
        for event in bible.timeline:
            lines.append(
                f"| {event.date} | {event.title} | {event.description} |"
            )
        lines.append("")
        for event in bible.timeline:
            lines.append(f"### {event.title}")
            lines.append("")
            if event.date:
                lines.append(f"- Date: {event.date}")
            if event.description:
                lines.append(event.description)
            if event.related_characters:
                lines.append(f"- Related characters: {', '.join(event.related_characters)}")
            if event.related_settings:
                lines.append(f"- Related settings: {', '.join(event.related_settings)}")
            lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "Generated by kdp-series-bible. Copyright (c) 2026 Asdale Dynamics, LLC. "
        "MIT Licensed."
    )

    return "\n".join(lines)


def load_bible(directory: str | Path) -> Bible:
    return Storage(directory).load()


def save_bible(bible: Bible, directory: str | Path) -> None:
    Storage(directory).save(bible)


def export_markdown(bible: Bible, path: Optional[str | Path] = None) -> str:
    """Render the bible as Markdown and return it (optionally write to file)."""
    markdown = render_markdown(bible)
    if path is not None:
        out_path = Path(path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(markdown, encoding="utf-8")
    return markdown
